// 2.2.16. A radioactive nucleus decayed into three
// fragments of masses m₁, m₂ and m₃, whose velocities
// v₁, v₂ and v₃, respectively, are mutually
// perpendicular. What was the velocity of the nucleus
// before the decay?
//
// We can calculate the total momentum after the decay:
// p = √(p₁² + p₂² + p₃²), before the decay the
// momenum of the nucleus is (m₁ + m₂ + m₃)υ, zo
//
// υ = √[(m₁υ₁)² + (m₂υ₂)² + (m₃υ₃)²]/(m₁ + m₂ + m₃)
//
