vector<i32> manachers( const string& s ){ // odd
  const i32 n = siz( s );
  vector<i32> d( n, 1 );
  i32 l, r = 0;
  for( i32 i = 1; i < n - 1; ++i ){
    if( i < r ){
      d[i] = min( r - i, d[l + (r - i)] );
    }
    while( s[i + d[i]] == s[i - d[i]] ) ++d[i];

    if( i + d[i] > r ){
      l = i - d[i];
      r = i + d[i];
    }
  }
  return d;
}
//////////////////////////////////////////////////////
string tricky_string( const string& s ){
  const i32 n = siz( s );
  string t( 2*n + 3, ' ' );
  t.front() = '^';
  t.back() = '$';
  for( i32 i = 0; i < n; ++i ){
    t[2*i + 2] = s[i];
  }
  return t;
}
//////////////////////////////////////////////////////
vector<i32> getp( const string& s ){
  const i32 n = siz( s );
  auto t = tricky_string( s ); dbg( t );
  auto d = manachers( t ); dbg( d );

  i32 start = 3;
  i32 finish = siz( d ) - 3;
  vector<i32> p( n, 1 );
  for( i32 i = start; i < finish; ++i ){
    i32 l = d[i] - 1; // length of palindrome
    if( l < 2 ) continue;
    i32 j = i/2 - 1;  // string index
    i32 e = j + l/2;  // ending
    for(; l > p[e]; --e, l -= 2 ){
      p[e] = l;        
    }}
  return p;
}
