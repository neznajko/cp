template <auto CROSS>
vector<Point> build_hull() {
  vector<Point> h;
  h.push_back( p[ 0 ]);
  h.push_back( p[ 1 ]);
  for( i32 i = 2; i < n; ++i ){
    auto j = siz( h ) - 1;
    while(( j > 0 ) and CROSS( h[j] - h[j-1], p[i] - h[j] )){
      h.pop_back();
      --j;
    }
    h.push_back( p[i] );
  }
  return h;
}
