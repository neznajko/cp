constexpr i32 XBOUND = 1e6 + 1;
vector<i32> sieve( XBOUND );
vector<i32> pc( XBOUND ); // prime counter
//////////////////////////////////////////////////////
void bld_sieve() {
  for( i32 x = 2; x < XBOUND; ++x ){
    if( sieve[x] ) continue;
    for( i32 y = x; y < XBOUND; y += x ){
      if( sieve[y] ) continue;
      sieve[y] = x;
    }}}
//////////////////////////////////////////////////////
//////////////////////////////////////////////////////
//////////////////////////////////////////////////////
//////////////////////////////////////////////////////
vector<i32> get_primes( i32 x ){ // x > 1
  vector<i32> primes{ sieve[x] };
  x /= sieve[x];
  while( x > 1 ){
    if( sieve[x] != primes.back()){
      primes.push_back( sieve[x] );
    }
    x /= sieve[x];
  }
  return primes;
}
//////////////////////////////////////////////////////
// least significant bit popping
i32 lpop( i32& x ){
  i32 n = __builtin_ctz( x );
  x ^= 1 << n;
  return n;
}
//////////////////////////////////////////////////////
//////////////////////////////////////////////////////
void pusk() {
  auto n = loads<i32>(); dbg( n );
  auto x = loadv<i32>( n ); dbg( x );
  bld_sieve();
  i64 tot = 0;
  for( i32 i = 0; i < n; ++i ){
    if( x[i] == 1 ){
      tot += i;
      continue;
    }
    auto p = get_primes( x[i] );
    dbg2( x[i], p );
    i64 sum = 0; // inclusion-exclusion
    i32 N = 1 << siz( p );
    // loop over subsets
    for( i32 k = 1; k < N; ++k ){
      i32 prod = 1;
      auto y = k;
      do {
        prod *= p[ lpop( y )];
      } while( y );
      if( __builtin_parity( k )){
        sum += pc[ prod ];
      } else {
        sum -= pc[ prod ];
      }
      ++pc[ prod ];
    }
    tot += i - sum;
  }
  cout << tot << nl;
}
