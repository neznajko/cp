constexpr int64_t MOD = 1e9+7;
constexpr int32_t ABCOUNT = 26;
int64_t dp( const string& s ){
  int32_t n = s.size();
  vector<int64_t> f( n + 1, 1 );
  vector<int32_t> last( ABCOUNT, -1 );
  for( int32_t i = 0; i < n; ++i ){
    f[i+1] = 2 * f[i] % MOD;
    int32_t& j = last[ s[i] - 'a' ];
    if( j != -1 ){
      f[i+1] = (f[i+1] + MOD - f[j]) % MOD;
    }
    j = i;
  }
  return (f[n] + MOD - 1) % MOD;
}
void pusk() {
  string s; cin >> s;
  cout << dp( s ) << nl;
}
