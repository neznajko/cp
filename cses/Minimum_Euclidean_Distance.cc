void mindist()
{
  i64 d2 = LLONG_MAX;
  auto cmp = []( const Point& a, const Point& b ){
    if( a.y == b.y ) return ( a.x < b.x );
    return ( a.y < b.y );
  };
  set<Point, decltype( cmp )> window( cmp );
  window.insert( p[0] );
  i64 LBond = d2;
  for( i32 j = 1; j < n; ++j ){
    auto prev = p[j-1].x;
    auto curr = p[j].x;
    i64 d = sqrt( d2 );
    if( prev + d < curr ){
      window.clear();
      LBond = curr;
    } else {
      auto JBond = curr - d; // James is too old!
      auto it = lower_bound( on( p ), LBond,
        []( const Point& q, i64 val ){
          return ( q.x < val );
        });
      for( i32 j = it - p.begin();
           j < n && p[j].x < JBond; ++j ){
        window.erase( p[j] );
      }
      LBond = JBond; // atarashii a ge n to 007.141529
      for( auto jt = window.lower_bound({ 0, p[j].y - d });
           jt != window.end() and jt->y <= p[j].y + d; ++jt ){
        d2 = min( d2, dist2( p[j], *jt ));
      }
    }
    window.insert( p[j] );
  }
  cout << d2 << nl;
}
