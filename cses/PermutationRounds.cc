///   0 1 2 3 4 5 6 7 8
// p=[0 5 3 2 6 4 1 8 7]
// 1->5->4->6->1
// 2->3->2
// 7->8->7
//
vector<i32> getT( const vector<i32>& p ){
  const auto n = siz( p );
  
  vector<i32> gcycle( n ); // cycle group
  i32 g = 0;
  vector<i32> T( 1 );

  for( i32 i = 1; i < n; ++i ){
    
    if( gcycle[i] ) continue;
    ++g;
    T.push_back( 0 );

    i32 j = i;
    do {
      gcycle[j] = g;
      j = p[j];
      ++T.back();
    } while( j != i );
  }
  dbg( gcycle );
  dbg( T );
  return T;
}
//////////////////////////////////////////////////////
vector<i32> sieve;
//////////////////////////////////////////////////////
void bld( i32 n ){
  sieve.resize( n + 1 );
  for( i32 x = 2; x <= n; ++x ){
    if( sieve[ x ]) continue;
    for( i32 y = x; y <= n; y += x ){
      if( sieve[ y ]) continue;
      sieve[y] = x;
    }
  }
}
//////////////////////////////////////////////////////
vector<i32> getmaxf( const vector<i32>& T ){
  i32 m = *max_element( on( T ));
  bld( m );
  dbg( sieve );
  vector<i32> maxf( m + 1, 1 );
  for( i32 j = siz( T ) - 1; j > 0; --j ){
    i32 x = T[j];
    vector<i32> f( m + 1, 1 );
    while( x > 1 ){
      i32 p = sieve[x];
      f[p] *= p;
      x /= p;
    }
    dbg2( T[j], f );
    for( i32 i = siz( maxf ) - 1; i >= 0; --i ){
      if( f[i] > maxf[i] ) maxf[i] = f[i];
    }
  }
  return maxf;
}
