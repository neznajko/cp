constexpr i64 MOD = 1e9 + 7;
//////////////////////////////////////////////////////
void pusk() {
  auto n = loads<i32>(); dbg( n );
  // let's make it base-1
  vector<i32> p( n + 1 );
  for( i32 j = 0; j < n; ++j ){
    cin >> p[j + 1];
  }
  dbg( p );
  auto T = getT( p );
  auto maxf = getmaxf( T );
  dbg( maxf );
  i64 rounds = 1;
  for( i32 j = siz( maxf ) - 1; j > 1; --j ){
    if( maxf[j] == 1 ) continue;
    rounds = rounds * maxf[j] % MOD;
  }
  cout << rounds << nl;
}
