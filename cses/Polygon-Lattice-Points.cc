using P = pair<i64,i64>;
# define X first
# define Y second

i64 get2S( const vector<P>& p ){
  i64 s = 0;
  for( i32 j = siz( p ) - 1; j > 0; --j ){
    s += p[j].X * p[j-1].Y - p[j-1].X * p[j].Y;
  }
  return abs( s );
}
