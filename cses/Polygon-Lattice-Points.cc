i64 getB( const vector<P>& p ){
  i64 b = 0;
  for( i32 j = siz( p ) - 1; j > 0; --j ){
    b += gcd( p[j].X - p[j-1].X, p[j].Y - p[j-1].Y ) - 1;
  }
  return siz( p ) - 1 + b;
}
