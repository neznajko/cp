vector<pair<i32,i32>> decode( const vector<i32>& code ){
  const auto n = siz( code ) + 2;
  vector<i32> deg( n + 1, 1 );
  deg[0] = 0;

  for( auto v: code ){ ++deg[v]; } dbg( deg );

  priority_queue<i32> leaf;
  for( i32 v = 1; v <= n; ++v ){
    if( deg[v] == 1 ) leaf.push( -v );
  }

  vector<pair<i32,i32>> edge;
  for( auto v: code ){
    auto u = -leaf.top(); leaf.pop();
    edge.emplace_back( u, v );
    if( --deg[v] == 1 ) leaf.push( -v );
  }
  auto u = -leaf.top(); leaf.pop();
  auto v = -leaf.top(); leaf.pop();
  edge.emplace_back( u, v );
  dbg( edge );
  return edge;
}
